// Build first, then: node test/studio-smoke.cjs
// Uses an installed Playwright + /usr/bin/chromium. No external services or AI calls.
const assert = require('node:assert/strict')
const { mkdtempSync, rmSync } = require('node:fs')
const { tmpdir } = require('node:os')
const { join } = require('node:path')
const { randomBytes } = require('node:crypto')
const { once } = require('node:events')
const { chromium } = require('playwright')

async function run() {
  const { createStudioServer } = await import('../server/index.mjs')
  const directory = mkdtempSync(join(tmpdir(), 'ielts-browser-'))
  const password = randomBytes(24).toString('hex')
  const server = createStudioServer({ password, dataDir: directory, secureCookie: false })
  server.listen(0, '127.0.0.1')
  await once(server, 'listening')
  const origin = `http://127.0.0.1:${server.address().port}`
  let browser
  const errors = []
  try {
    browser = await chromium.launch({ executablePath: '/usr/bin/chromium', headless: true, args: ['--no-sandbox', '--use-fake-device-for-media-stream', '--use-fake-ui-for-media-stream'] })
    const desktop = await browser.newContext({ viewport: { width: 1440, height: 1050 }, permissions: ['microphone'] })
    const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, permissions: ['microphone'] })
    const a = await desktop.newPage()
    const b = await mobile.newPage()
    for (const page of [a, b]) {
      page.on('pageerror', error => errors.push(error.message))
      await page.route('**/*', route => route.request().url().startsWith(origin) || route.request().url().startsWith('blob:') ? route.continue() : route.abort())
    }
    async function go(page, path) { await page.goto(`${origin}/#${path}`); await page.locator('.studio-page').waitFor() }
    async function login(page) {
      await go(page, '/settings')
      await page.getByLabel('私人访问口令').fill(password)
      await page.getByRole('button', { name: '登录并同步' }).click()
      await page.getByRole('heading', { name: '已连接私人同步服务' }).waitFor()
      await page.getByRole('status').filter({ hasText: '已连接私人服务' }).waitFor()
    }
    async function sync(page) {
      await go(page, '/settings')
      await page.getByRole('button', { name: '立即同步' }).click()
      await page.waitForFunction(() => document.querySelector('.studio-connection')?.textContent.includes('已同步'))
    }
    await go(a, '/')
    await a.getByRole('heading', { name: /练习有方向/ }).waitFor()
    await a.screenshot({ path: '/tmp/ielts-studio-desktop.png', fullPage: true })
    await login(a)
    await go(a, '/train?prompt=w-study')
    const first = 'Universities should prepare students for work, but they should also encourage research. For example, research into public health can benefit society even when it does not produce an immediate commercial return.'
    await a.getByLabel('你的英文作答').fill(first)
    await a.reload()
    await assert.equal(await a.getByLabel('你的英文作答').inputValue(), first)
    await a.getByRole('button', { name: '提交并进入复盘' }).click()
    await a.getByLabel('02 · 这次只聚焦一个改进点').selectOption('观点与论证')
    await a.getByLabel('证据、原因与下一次的具体行动').fill('The example lacks detail. In the retry, explain how public-health research benefits people.')
    await a.getByRole('button', { name: '能独立完成 · 拉开间隔' }).click()
    await a.getByRole('status').filter({ hasText: '3 天后' }).waitFor()
    const firstURL = a.url()
    await a.getByRole('button', { name: '带着改进点，同题重练' }).click()
    await a.getByLabel('你的英文作答').waitFor()
    assert.notEqual(a.url(), firstURL)
    assert.equal(await a.getByLabel('你的英文作答').inputValue(), '')
    await a.getByLabel('你的英文作答').fill(`${first} Public-health researchers can identify the causes of disease, allowing governments to prevent illness rather than merely pay for treatment.`)
    await a.getByRole('button', { name: '提交并进入复盘' }).click()
    await a.getByLabel('证据、原因与下一次的具体行动').fill('Added a clear causal explanation. Next time check whether each paragraph connects to the question.')
    await a.getByRole('button', { name: '能独立完成 · 拉开间隔' }).click()
    await a.getByRole('status').filter({ hasText: '6 天后' }).waitFor()
    await sync(a)
    await login(b)
    await go(b, '/review')
    await b.getByRole('button', { name: /全部记录/ }).click()
    assert.equal(await b.locator('article.review-card').count(), 2)
    await b.screenshot({ path: '/tmp/ielts-studio-mobile.png', fullPage: true })
    assert.equal(await b.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false)
    console.log('PASS: draft recovery, revision history, expanding schedule, desktop-to-phone sync, mobile layout')

    await go(a, '/train?prompt=w-transport')
    await a.getByLabel('你的英文作答').fill('A draft started on my laptop.')
    const draftURL = a.url()
    await sync(a)
    await sync(b)
    await b.goto(draftURL)
    await b.getByLabel('你的英文作答').waitFor()
    assert.equal(await b.getByLabel('你的英文作答').inputValue(), 'A draft started on my laptop.')
    await b.getByLabel('你的英文作答').fill('A draft revised on my phone.')
    await sync(b)
    await sync(a)
    await a.goto(draftURL)
    assert.equal(await a.getByLabel('你的英文作答').inputValue(), 'A draft revised on my phone.')
    console.log('PASS: phone-to-desktop draft sync')

    await b.goto(draftURL)
    await b.getByLabel('你的英文作答').waitFor()
    await desktop.setOffline(true)
    await mobile.setOffline(true)
    await a.getByLabel('你的英文作答').fill('An independent offline laptop revision.')
    await b.getByLabel('你的英文作答').fill('An independent offline phone revision.')
    await mobile.setOffline(false)
    await b.evaluate(() => window.dispatchEvent(new Event('online')))
    await b.waitForFunction(() => document.querySelector('.studio-connection')?.textContent.includes('已同步'))
    await desktop.setOffline(false)
    await a.evaluate(() => window.dispatchEvent(new Event('online')))
    await a.waitForFunction(oldURL => location.href !== oldURL, draftURL)
    await sync(a)
    const records = await a.evaluate(async () => (await fetch('/api/attempts')).json())
    assert.ok(records.some(row => row.text === 'An independent offline laptop revision.'))
    assert.ok(records.some(row => row.text === 'An independent offline phone revision.'))
    assert.equal(records.length, 4)
    console.log('PASS: simultaneous offline edits preserve both versions without false conflict copies')

    await go(a, '/train?prompt=r-retrieval')
    await a.getByRole('button', { name: '提交并进入复盘' }).click()
    await a.getByRole('alert').filter({ hasText: '请先回答所有题目' }).waitFor()
    for (const [id, answer] of Object.entries({ 1: 'FALSE', 2: 'TRUE', 3: 'NOT GIVEN', 4: 'FALSE' })) await a.locator(`#q-${id}`).selectOption(answer)
    await a.locator('#q-5').fill('evidence')
    await a.locator('#q-6').fill('retention')
    await a.getByRole('button', { name: '提交并进入复盘' }).click()
    await a.getByText('本次答对 6 / 6。先解释错误原因，再决定复习间隔。').waitFor()
    assert.equal(await a.locator('.evidence').count(), 6)
    console.log('PASS: reading requires answers, marks correctly and exposes passage evidence after submission')

    await go(a, '/train?prompt=s-learning')
    await a.getByRole('button', { name: '开始录音', exact: true }).click()
    await a.locator('.recording-light').waitFor()
    await a.waitForTimeout(1500)
    await a.getByRole('button', { name: '停止并保存录音' }).click()
    await a.locator('audio').waitFor()
    await a.getByText('录音已保存到本机。连接服务后会自动上传。').waitFor()
    const audioURL = a.url()
    assert.equal(await a.getByRole('button', { name: 'AI 转写 · 按次调用' }).isDisabled(), true)
    await a.getByLabel('回答转写 / 手动输入').fill('I would like to learn photography because I enjoy recording everyday life.')
    await a.getByRole('button', { name: '提交并进入复盘' }).click()
    await sync(a)
    await sync(b)
    await b.goto(audioURL)
    await b.locator('audio').waitFor()
    await b.waitForFunction(() => document.querySelector('audio')?.readyState >= 2)
    await b.locator('audio').evaluate(async audio => { await audio.play(); audio.pause() })
    console.log('PASS: real MediaRecorder capture, IndexedDB persistence, authenticated audio sync and phone playback source')
    assert.deepEqual(errors, [])
    console.log('PASS: no JavaScript page errors; no paid APIs called')
  }
  finally {
    if (browser) await browser.close()
    await new Promise(resolve => server.close(resolve))
    rmSync(directory, { recursive: true, force: true })
  }
}
run().catch(error => { console.error(error); process.exitCode = 1 })
